func TestInvalidConfigFailsWithClearErrorAndExitCode2(t *testing.T) {
	cases := []struct {
		name, config, mention string
	}{
		{"malformed TOML", "[weights\ncomplexity = 1\n", "entropic.toml"},
		{"unknown key", "exclud = [\"gen\"]\n", "exclud"},
		{"unknown Signal weight", "[weights]\ncomplexty = 1\n", "complexty"},
		{"negative weight", "[weights]\ncomplexity = -1\n", "complexity"},
		{"wrong type", "exclude = \"gen\"\n", "exclude"},
		{"bad exclude pattern", "exclude = [\"gen/[\"]\n", "gen/["},
		{"non-positive churn window", "churn_window_days = 0\n", "churn_window_days"},
		{"non-positive duplicate minimum size", "duplicate_min_lines = -3\n", "duplicate_min_lines"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			repo := testrepo.New(t).
				Write("calc/calc.go", calcGo).
				Write("entropic.toml", c.config).
				Commit("add calc and config")

			res := repo.Run("--base", "none")

			if res.Code != 2 {
				t.Errorf("exit code: want 2, got %d", res.Code)
			}
			if res.Stdout != "" {
				t.Errorf("want no report on stdout, got %s", res.Stdout)
			}
			if !strings.Contains(res.Stderr, c.mention) {
				t.Errorf("stderr should mention %q, got %q", c.mention, res.Stderr)
			}
		})
	}
}
