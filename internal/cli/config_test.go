func TestConfigWeightsChangeEntropyScore(t *testing.T) {
	repo := testrepo.New(t).
		Write("calc/calc.go", calcGo).
		Write("entropic.toml", "[weights]\ncomplexity = 2\n").
		Commit("add calc and config")

	r := repo.Run("--base", "none").Report(0)

	// Complexity 4, weighted 2, per 16 non-blank lines = 50 per 100 lines.
	if r.EntropyScore.Value != 50 {
		t.Errorf("entropyScore: want 50, got %v", r.EntropyScore.Value)
	}
}

const flatGo = "package p\n\nfunc F() {}\n"

// paths returns the path of every file Unit in a report.
func paths(units []testrepo.ReportUnit) []string {
	var out []string
	for _, u := range units {
		out = append(out, u.Path)
	}
	return out
}

