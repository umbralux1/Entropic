// Package python is the language adapter for Python.
package python

import (
	"regexp"

	sitter "github.com/tree-sitter/go-tree-sitter"
	tspython "github.com/tree-sitter/tree-sitter-python/bindings/go"

	"github.com/umbralux1/entropic/internal/analysis"
)

// Language tells analysis how to read Python.
var Language = analysis.Language{
	Name:       "python",
	Grammar:    sitter.NewLanguage(tspython.Language()),
	Extensions: []string{".py"},
	Functions: map[string]bool{
		"function_definition": true,
	},
	Classes: map[string]bool{
		"class_definition": true,
	},
	UnitName:   unitName,
	Complexity: complexity,
	Cyclomatic: cyclomatic,
	// vendor by general convention, _vendor as pip and setuptools do,
	// site-packages for a checked-in environment.
	VendorDirs: []string{"vendor", "_vendor", "site-packages"},
	// pytest's default discovery patterns and its conftest.py, plus test
	// and tests directories.
	TestFiles: []string{"test_*.py", "*_test.py", "conftest.py"},
	TestDirs:  []string{"test", "tests"},
	// protoc's marker, the Go convention some Python generators reuse, and
	// the cross-language @generated tag, each as a leading comment line.
	Generated: regexp.MustCompile(
		`(?m)^# (?:Generated by .*DO NOT EDIT|Code generated .* DO NOT EDIT\.$|@generated\b)`),
	Abstracted: map[string]bool{
		"identifier":          true,
		"integer":             true,
		"float":               true,
		"string":              true,
		"concatenated_string": true,
	},
	IgnoredByDuplication: map[string]bool{
		"import_statement":        true,
		"import_from_statement":   true,
		"future_import_statement": true,
		"comment":                 true,
	},
}

// unitName qualifies a definition's name with the classes it is in, so that
// same-named methods in different classes stay distinct: Outer.Inner.method.
func unitName(def *sitter.Node, source []byte) string {
	name := def.ChildByFieldName("name").Utf8Text(source)
	for p := def.Parent(); p != nil; p = p.Parent() {
		if p.Kind() == "class_definition" {
			name = p.ChildByFieldName("name").Utf8Text(source) + "." + name
		}
	}
	return name
}
